  function setLang(lang) {
    currentLang = (lang === 'en') ? 'en' : 'zh';
    if (typeof document !== 'undefined' && document.documentElement) {
      document.documentElement.lang = currentLang === 'en' ? 'en' : 'zh-CN';
      document.title = t('app.title');
    }
    return currentLang;
  }

  function t(key, vars) {
    var table = DICT[currentLang] || DICT.zh;
    var str = Object.prototype.hasOwnProperty.call(table, key)
      ? table[key]
      : (Object.prototype.hasOwnProperty.call(DICT.zh, key) ? DICT.zh[key] : key);
    if (!vars) return str;
    return str.replace(/\{([a-zA-Z0-9_]+)\}/g, function (_, k) {
      return (vars[k] === undefined || vars[k] === null) ? '' : String(vars[k]);
    });
  }

  function labelName(index) {
    var list = LABELS[currentLang] || LABELS.zh;
    var i = Number(index);
    if (!Number.isFinite(i) || i < 0) i = 0;
    return list[i % list.length];
  }

  function kindLabel(kind) {
    var map = KINDS[currentLang] || KINDS.zh;
    return map[kind] || map.other;
  }

  function columnLabel(colId) {
    var map = COLUMNS[currentLang] || COLUMNS.zh;
    return map[colId] || colId;
  }

